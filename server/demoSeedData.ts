/**
 * Ensures that the in-memory DatabaseState has all comprehensive demo data:
 * - Dr. Prashant upgraded to senior pediatrician credentials
 * - All 10 test kids have full allergies, chronic conditions, growth records & past prescriptions
 * - Today's appointments cover all 10 kids at various times across morning and afternoon OPD
 */
export function ensureComprehensiveDemoData(state: DatabaseState): void {
  const targetDate = state.config?.simulatedDate || new Date().toISOString().split('T')[0];

  // 1. Upgrade Dr. Prashant's credentials to match Dr. Subba Rao
  const prashantDoc = state.doctors.find((d) => d.id === 'dr-prashant');
  if (prashantDoc) {
    prashantDoc.qualifications = 'MBBS, MD (Pediatrics), DCH, FIAP';
    prashantDoc.specialty = 'Senior Consultant Pediatrician & Neonatologist';
    prashantDoc.experienceYears = 24;
    prashantDoc.summary =
      'Senior experienced pediatrician with 24+ years of clinical excellence in neonatal intensive care, pediatric infectious diseases, pediatric asthma, and growth development.';
    prashantDoc.medicalRegistrationNo = 'APMC-45120';
  }

  const prashantAccount = state.doctorAccounts.find((a) => a.doctorId === 'dr-prashant');
  if (prashantAccount) {
    prashantAccount.medicalRegistrationNo = 'APMC-45120';
  }

  // 2. Merge Allergies
  const demoAllergies = getDemoAllergies(targetDate);
  const existingAlgMap = new Map(state.allergies.map((a) => [a.id, a]));
  for (const alg of demoAllergies) {
    existingAlgMap.set(alg.id, alg);
  }
  state.allergies = Array.from(existingAlgMap.values());

  // 3. Merge Conditions
  const demoConditions = getDemoConditions(targetDate);
  const existingCndMap = new Map(state.conditions.map((c) => [c.id, c]));
  for (const cnd of demoConditions) {
    existingCndMap.set(cnd.id, cnd);
  }
  state.conditions = Array.from(existingCndMap.values());

  // 4. Merge Growth Records
  const demoGrowth = getDemoGrowthRecords(targetDate);
  const existingGrMap = new Map(state.growthRecords.map((g) => [g.id, g]));
  for (const gr of demoGrowth) {
    existingGrMap.set(gr.id, gr);
  }
  state.growthRecords = Array.from(existingGrMap.values());

  // 5. Merge Past Encounters & Prescriptions
  const demoEncounters = getDemoEncounters(targetDate);
  const existingEncMap = new Map(state.encounters.map((e) => [e.id, e]));
  for (const enc of demoEncounters) {
    existingEncMap.set(enc.id, enc);
  }
  state.encounters = Array.from(existingEncMap.values());

  // 6. Ensure Active Doctor Sessions exist for both doctors
  const doctors = ['dr-subba-rao', 'dr-prashant'];
  const branches = ['kakinada', 'pithapuram'];
  for (const docId of doctors) {
    for (const bId of branches) {
      const hasSession = state.sessions.some(
        (s) => s.doctorId === docId && s.branchId === bId && s.date === targetDate
      );
      if (!hasSession) {
        state.sessions.push({
          doctorId: docId,
          branchId: bId as any,
          date: targetDate,
          scheduledStart: '10:00',
          actualStart: docId === 'dr-subba-rao' ? '10:00' : '10:00',
          status: 'IN_SESSION',
          currentAppointmentId: docId === 'dr-subba-rao' ? 'apt-4' : 'apt-p2',
          currentDelayMinutes: 0,
          avgConsultationDurationMinutes: 14,
          bufferAvailableMinutes: 20,
          emergencyAdjustmentCount: 0,
        });
      }
    }
  }

  // 7. Ensure Appointments for all 10 kids on targetDate
  const demoAppointments = getDemoAppointments(targetDate);
  const existingApptMap = new Map(state.appointments.map((a) => [a.id, a]));

  for (const appt of demoAppointments) {
    const existing = existingApptMap.get(appt.id);
    if (!existing || existing.date !== targetDate) {
      existingApptMap.set(appt.id, appt);
    }
  }

  // Also check if any appointment with targetDate has old dates and update
  state.appointments = Array.from(existingApptMap.values());
}
